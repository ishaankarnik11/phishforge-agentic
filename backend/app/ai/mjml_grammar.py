"""MJML grammar contract for the AI prompts (STORY-7.11).

The contract block injected into the system prompts of the generator and
refiner is **derived from MJML's component registry** — never hand-written.
Source of truth is :mod:`app.services.mjml_sanitize` /
``backend/app/services/mjml_void_tags.json``, which is regenerated by
``backend/scripts/dump_mjml_void_tags.js`` from the installed ``mjml``
package's ``components`` map and ``mjml-validator`` dependency graph.

The dump already carries everything we need per tag:

* ``name`` — the MJML element name.
* ``endingTag`` — true for text-content tags (``mj-text``, ``mj-button``,
  ``mj-style`` etc.) which accept inner text but not nested mj-* children.
* ``allowedChildren`` — the validator's whitelist of legal child tags.
  ``[]`` means **void** (must self-close), ``null`` means "no entry in
  the dependency graph" (treated conservatively as opaque).
* ``isVoid`` — ``true`` iff the tag is registered, has ``endingTag !== true``,
  and an empty ``allowedChildren`` list.

We compute the inverse — ``allowedParents`` — at module load by scanning
``allowedChildren`` for every tag.

The grammar block is **stable across calls**: same registry → same string.
That stability is load-bearing for prompt caching (CLAUDE.md rule).

The block is appended to the system prompt before the dynamic brand kit
context. Both sit in the **system block** with ``cache_control: ephemeral``
applied by ``LlmClient`` so they cache together.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

# The JSON file is the same one the sanitizer reads. Single source of truth.
_VOID_TAGS_JSON = (
    Path(__file__).parent.parent / "services" / "mjml_void_tags.json"
).resolve()


def _load_registry() -> tuple[list[dict[str, Any]], str]:
    """Return ``(tags, mjml_version)`` from the dumped registry."""
    with _VOID_TAGS_JSON.open("r", encoding="utf-8") as fh:
        payload = json.load(fh)
    tags: list[dict[str, Any]] = payload.get("tags", [])
    version = str(payload.get("mjmlVersion", "unknown"))
    return tags, version


# ---------------------------------------------------------------------------
# Allowlist of tags we expose to the LLM
# ---------------------------------------------------------------------------
#
# The spec (STORY-7.11 AC-1) lists the tag set the LLM is allowed to emit.
# We keep this hand-list small and Sprint-2 specific — exposing every
# component MJML ships (eg. mj-accordion, mj-navbar-link) only invites the
# LLM to invent layouts the brand-validator and downstream review flow
# don't yet support. Each tag MUST appear in the registry; we assert that
# on load to fail fast if a future MJML upgrade renames anything.

ALLOWED_HEAD_TAGS: tuple[str, ...] = (
    "mj-head",
    "mj-attributes",
    "mj-style",
    "mj-font",
)

ALLOWED_BODY_TAGS: tuple[str, ...] = (
    "mj-body",
    "mj-section",
    "mj-column",
    "mj-text",
    "mj-image",
    "mj-button",
    "mj-divider",
    "mj-spacer",
    "mj-raw",
    "mj-table",
    "mj-wrapper",
    "mj-group",
    "mj-social",
    "mj-social-element",
    "mj-navbar",
    "mj-navbar-link",
    "mj-hero",
    "mj-carousel",
    "mj-carousel-image",
)

ALLOWED_TAGS: frozenset[str] = frozenset(
    ("mjml",) + ALLOWED_HEAD_TAGS + ALLOWED_BODY_TAGS
)


def _build_grammar_block() -> tuple[str, list[str]]:
    """Render the grammar contract block. Returns (block_text, void_tag_names)."""
    tags, mjml_version = _load_registry()
    by_name: dict[str, dict[str, Any]] = {t["name"]: t for t in tags}

    # Per-tag allowedParents inferred from every other tag's allowedChildren.
    parents_of: dict[str, set[str]] = {}
    for entry in tags:
        children = entry.get("allowedChildren") or []
        for child in children:
            if not isinstance(child, str):
                continue  # skip the {} placeholder mj-attributes uses
            parents_of.setdefault(child, set()).add(entry["name"])

    # Verify every name in our hand-list is present in the registry. If a
    # future mjml upgrade renames or drops a tag this fails the test.
    missing = [n for n in ALLOWED_HEAD_TAGS + ALLOWED_BODY_TAGS if n not in by_name]
    if missing:
        raise RuntimeError(
            f"mjml_void_tags.json is missing tags listed in ALLOWED_*: {missing}. "
            "Re-run backend/scripts/dump_mjml_void_tags.js after upgrading mjml."
        )

    void_tags = sorted(t["name"] for t in tags if t.get("isVoid"))

    lines: list[str] = []
    lines.append("MJML GRAMMAR CONTRACT")
    lines.append(f"(derived from MJML component registry @ mjml@{mjml_version} — ")
    lines.append("see docs/MJML_CONTRACT.md for the source of truth)")
    lines.append("")
    lines.append("ALLOWED TAGS (do NOT emit anything outside this list):")
    lines.append("  Head: " + ", ".join(ALLOWED_HEAD_TAGS))
    lines.append("  Body: " + ", ".join(ALLOWED_BODY_TAGS))
    lines.append("")
    lines.append("PER-TAG RULES (parent / children / void):")

    # Stable column widths for human + LLM readability.
    name_w = max(len(n) for n in ALLOWED_HEAD_TAGS + ALLOWED_BODY_TAGS) + 2

    for name in ALLOWED_HEAD_TAGS + ALLOWED_BODY_TAGS:
        entry = by_name[name]
        is_void = bool(entry.get("isVoid"))
        ending_tag = bool(entry.get("endingTag"))
        children_field = entry.get("allowedChildren")
        if is_void:
            children_str = "VOID — no children, must self-close"
        elif ending_tag:
            children_str = "text/HTML content (no nested mj-*)"
        elif isinstance(children_field, list) and children_field:
            child_names = [c for c in children_field if isinstance(c, str)]
            if child_names:
                children_str = "children: " + ", ".join(sorted(child_names))
            else:
                # mj-attributes uses [{}] meaning "any attribute element"
                children_str = "children: any mj-* attribute element"
        else:
            children_str = "children: (registry has no entry — use sparingly)"

        # Build parent string. mjml is the implicit root; mj-head / mj-body
        # are the only legal children of mjml.
        parents = sorted(parents_of.get(name, set()))
        if name == "mjml":
            parent_str = "parent: (root)"
        elif name in ("mj-head", "mj-body"):
            parent_str = "parent: mjml"
        elif parents:
            parent_str = "parent: " + ", ".join(parents)
        else:
            parent_str = "parent: (registry has no entry)"

        lines.append(f"  {name.ljust(name_w)}{parent_str}; {children_str}")

    lines.append("")
    lines.append(
        "VOID TAGS — MUST be self-closed (`<tag attrs/>`). NEVER wrap content "
        "with these. The compiler silently drops their children, which has "
        "previously caused 75%-truncated emails:"
    )
    for v in void_tags:
        lines.append(f"  - {v}")

    block = "\n".join(lines)
    return block, void_tags


# ---------------------------------------------------------------------------
# Failure → correction few-shot examples (AC-2)
# ---------------------------------------------------------------------------
#
# The visual delimiters (`# WRONG ❌` / `# RIGHT ✅`) are deliberate so the
# LLM cannot mistake the WRONG block for an example to imitate. We have
# observed Sonnet faithfully copying anything inside its system prompt that
# looked plausibly correct; the labelling cuts that failure mode.

_FEW_SHOT_BLOCK = """\
FAILURE → CORRECTION EXAMPLES
(Each pair shows a real failure mode that has truncated production emails. \
The WRONG form is what the validator rejects; the RIGHT form is what you \
MUST emit. Read both columns carefully — do not imitate the WRONG side.)

# Example 1 — void mj-divider used as a wrapper

# WRONG (do NOT emit):
<mj-divider>
  <mj-section>
    <mj-column>
      <mj-text>Body content</mj-text>
    </mj-column>
  </mj-section>
</mj-divider>

# RIGHT:
<mj-divider/>
<mj-section>
  <mj-column>
    <mj-text>Body content</mj-text>
  </mj-column>
</mj-section>

# Example 2 — mj-section directly under mj-body containing text without a column

# WRONG (do NOT emit):
<mj-body>
  <mj-section>
    <mj-text>Welcome</mj-text>
  </mj-section>
</mj-body>

# RIGHT:
<mj-body>
  <mj-section>
    <mj-column>
      <mj-text>Welcome</mj-text>
    </mj-column>
  </mj-section>
</mj-body>

# Example 3 — void mj-image written with an explicit closing tag

# WRONG (do NOT emit):
<mj-image src="https://example.com/logo.png"></mj-image>

# RIGHT:
<mj-image src="https://example.com/logo.png" alt="Example"/>
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


_GRAMMAR_BLOCK, _VOID_TAG_NAMES = _build_grammar_block()


def get_grammar_block() -> str:
    """Return the full grammar contract + few-shot block.

    Output is deterministic across calls so the prompt cache hits.
    """
    return f"{_GRAMMAR_BLOCK}\n\n{_FEW_SHOT_BLOCK}"


def get_void_tag_names() -> list[str]:
    """Return the registry-derived void-tag names (read-only snapshot)."""
    return list(_VOID_TAG_NAMES)


__all__ = [
    "ALLOWED_BODY_TAGS",
    "ALLOWED_HEAD_TAGS",
    "ALLOWED_TAGS",
    "get_grammar_block",
    "get_void_tag_names",
]
