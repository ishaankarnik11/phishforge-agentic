"""STORY-7.10 — assert ``mjml_void_tags.json`` is in sync with the installed mjml.

The sanitizer's auto-repair pass reads the void-tag list from
``backend/app/services/mjml_void_tags.json``.  That file is regenerated by
``backend/scripts/dump_mjml_void_tags.js``.  This test re-runs the dumper
and asserts the committed JSON matches — so a future ``mjml@`` upgrade
either regenerates the JSON or breaks CI.

Skipped when Node / mjml is not on PATH (e.g. CI image without npm).
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

BACKEND_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = BACKEND_ROOT / "scripts" / "dump_mjml_void_tags.js"
COMMITTED = BACKEND_ROOT / "app" / "services" / "mjml_void_tags.json"


def _node_available() -> bool:
    return bool(shutil.which("node") and shutil.which("npm"))


pytestmark = pytest.mark.skipif(
    not _node_available(),
    reason="node/npm not on PATH; cannot regenerate void-tag list",
)


def test_committed_void_tags_matches_installed_mjml() -> None:
    """Run the dumper and compare its output with the committed JSON."""
    assert SCRIPT.exists(), f"missing dumper script at {SCRIPT}"
    assert COMMITTED.exists(), f"missing committed JSON at {COMMITTED}"

    proc = subprocess.run(
        ["node", str(SCRIPT)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, (
        f"dumper exited {proc.returncode}\nstderr:\n{proc.stderr}"
    )

    fresh = json.loads(proc.stdout)
    committed = json.loads(COMMITTED.read_text(encoding="utf-8"))

    # Compare just the meaningful payload — version + tags list.  The
    # generatedBy field is identical by construction.
    assert fresh["mjmlVersion"] == committed["mjmlVersion"], (
        "Installed mjml version differs from the one captured in "
        f"{COMMITTED.name}.  Re-run "
        "`node backend/scripts/dump_mjml_void_tags.js > "
        "backend/app/services/mjml_void_tags.json` and commit."
    )
    assert fresh["tags"] == committed["tags"], (
        "MJML component registry has drifted from the committed snapshot. "
        "Re-run "
        "`node backend/scripts/dump_mjml_void_tags.js > "
        "backend/app/services/mjml_void_tags.json` and commit."
    )
